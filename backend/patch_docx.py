def get_full_text(para):
    """Повертає повний текст абзацу."""
    return ''.join(r.text or '' for r in para.runs)


def set_paragraph_text(para, new_text):
    """
    Замінює текст у першому run абзацу, очищає решту runs.
    Зберігає форматування першого run.
    """
    runs = para.runs
    if not runs:
        return
    # Записуємо весь текст у перший run
    runs[0].text = new_text
    # Очищаємо решту runs
    for r in runs[1:]:
        r.text = ''


def apply_replacement(text, old, new):
    """Замінює підрядок з урахуванням пробілів на початку/кінці."""
    return text.replace(old, new)


def main():
    # Резервна копія
    shutil.copy2(PATH, BACKUP)
    print(f'✓ Резервна копія: {BACKUP}')

    doc = Document(PATH)
    changed = 0

    for para in doc.paragraphs:
        original = get_full_text(para)
        if not original.strip():
            continue

        modified = original
        for old, new in REPLACEMENTS:
            if old in modified:
                modified = apply_replacement(modified, old, new)

        if modified != original:
            set_paragraph_text(para, modified)
            changed += 1
            print(f'  [ЗМІНЕНО] {original[:80]}...' if len(original) > 80 else f'  [ЗМІНЕНО] {original}')

    # Обробка таблиць
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    original = get_full_text(para)
                    if not original.strip():
                        continue
                    modified = original
                    for old, new in REPLACEMENTS:
                        if old in modified:
                            modified = apply_replacement(modified, old, new)
                    if modified != original:
                        set_paragraph_text(para, modified)
                        changed += 1
                        print(f'  [ТАБЛИЦЯ] {original[:70]}')

    doc.save(PATH)
    print(f'\n✓ Збережено: {PATH}')
    print(f'✓ Змінено абзаців: {changed}')


if __name__ == '__main__':
    main()
